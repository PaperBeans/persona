"""Go: one package, no dependencies. A union is one flat struct (its variants' fields, all optional) with the
discriminator: what the hub has always decoded views into."""

from __future__ import annotations

import json
import re
import shutil
import subprocess

from .model import Call, Def, Field, SchemaError, TypeRef, flat_fields, reserved_keys
from .names import camel, comment, go_field, named, plural, sentence


GO_HEADER = ["// Code generated by scripts/gen/extension_schema.py from schema/extension/. DO NOT EDIT."]
GO_PACKAGE_DOC = "// Package wire holds the extension protocol's and views' types (schema/extension/)."

def go_calls(calls: list[Call]) -> list[str]:
    if not calls:
        return []
    out = ["// Call is one call or event of an extension point's protocol (the schemas' x-methods and x-events): who",
           "// sends it (hub or program), and the definitions its params and its answer hold to (Result \"\" is any",
           "// JSON; an event has no answer).",
           "type Call struct {", "\tName, From, Params, Result string", "\tEvent                      bool", "}", "",
           "// Calls are the calls and events the schemas describe, by name as on the wire.",
           "var Calls = map[string]Call{"]
    for c in calls:
        ev = ", Event: true" if c.event else ""
        out.append(f"\t{json.dumps(c.name)}: {{Name: {json.dumps(c.name)}, From: {json.dumps(c.sender)}, "
                   f"Params: {json.dumps(c.params)}, Result: {json.dumps(c.result)}{ev}}},")
    return out + ["}", ""]



def gen_go(defs: dict[str, Def], calls: list[Call] | None = None, *, header: list[str] | None = None,
           package: str = "wire", package_doc: str = GO_PACKAGE_DOC, registry: str = "newDef",
           defects: str = "ExtensionWire", packages: dict[str, tuple[str, str]] | None = None) -> str:
    """Go for one package. A schema/wire file shares its package with hand-written code, so it gets no package doc
    (package_doc "") and its own registry name; it imports encoding/json only when its types use it. defects names the
    hook closed enums with x-unknown "count" call (<defects>UnknownEnum), one per file. packages: the import path and
    package name each shared file's IDs (Def.external) come from."""
    for d in defs.values():
        if d.external and d.external not in (packages or {}):
            raise SchemaError(f"{d.name} of {d.external}: no Go package to import it from")
    uses_time = any(f.type.kind == "time" for d in defs.values() for f in d.fields)
    out: list[str] = []

    def gtype(t: TypeRef, optional: bool, pointer: bool) -> str:
        k = t.kind
        if k == "string":
            return "*string" if pointer else "string"
        if k == "int":
            return "*int" if pointer else "int"
        if k == "int64":
            return "*int64" if pointer else "int64"
        if k == "number":
            return "*float64" if pointer else "float64"
        if k == "bool":
            if t.ref:  # x-tristate: absent, true and false as one value
                return t.ref
            return "*bool" if pointer else "bool"
        if k == "time":
            return "time.Time"
        if k == "any":
            return "json.RawMessage"
        if k == "array":
            return "[]" + gtype(t.of, False, False)
        if k == "map":
            return "map[string]" + gtype(t.of, False, False)
        d = defs[t.ref]
        if d.kind == "enum" and not d.closed:
            return "string"
        if d.kind in ("enum", "id", "text"):
            qualified = f"{packages[d.external][1]}.{t.ref}" if d.external else t.ref
            return ("*" if pointer else "") + qualified
        if d.kind == "opaque":
            return t.ref
        return ("*" if optional else "") + t.ref

    def field_line(f: Field, force_optional: bool = False) -> list[str]:
        optional = force_optional or not f.required
        typ = gtype(f.type, optional, f.pointer)
        tag = f.name
        if optional:
            # x-go-pointer on a list: an empty one means something (replaces), only a nil one is left out.
            tag += ",omitzero" if f.type.kind == "time" or f.type.kind == "array" and f.pointer or \
                f.type.kind == "bool" and f.type.ref else ",omitempty"
        return comment("\t// ", f.doc) + [f"\t{go_field(f.name)} {typ} `json:\"{tag}\"`"]

    # Preserve required native union fields only when reached from an explicitly preserving stream object.
    # Ancestor wrappers override native children, never the legacy public models' encoders.
    def refs(t: TypeRef) -> list[str]:
        if t.kind == "ref":
            return [t.ref]
        return refs(t.of) if t.of else []

    reachable: set[str] = set()

    def visit(name: str) -> None:
        if name in reachable:
            return
        reachable.add(name)
        d = defs[name]
        for f in flat_fields(defs, d) if d.kind == "union" else d.fields:
            for ref in refs(f.type):
                visit(ref)

    for d in defs.values():
        if d.preserve_required:
            visit(d.name)
    wrapped = {name for name in reachable if defs[name].kind == "union" and not defs[name].preserve_required}
    while True:
        ancestors = {name for name in reachable if not defs[name].preserve_required
                     and any(ref in wrapped for f in defs[name].fields for ref in refs(f.type))}
        if ancestors <= wrapped:
            break
        wrapped |= ancestors

    def wire_type(t: TypeRef, optional: bool, pointer: bool) -> str:
        if t.kind == "ref" and t.ref in wrapped:
            return ("*" if optional else "") + "requiredJSON" + t.ref
        if t.kind == "array":
            return "[]" + wire_type(t.of, False, False)
        if t.kind == "map":
            return "map[string]" + wire_type(t.of, False, False)
        return gtype(t, optional, pointer)

    def converted(t: TypeRef, value: str, optional: bool, pointer: bool) -> str:
        typ = wire_type(t, optional, pointer)
        if typ == gtype(t, optional, pointer):
            return value
        if t.kind == "ref":
            return f"({typ})({value})"
        if t.kind == "array":
            body = f"for i, item := range {value} {{ out[i] = {converted(t.of, 'item', False, False)} }}"
            allocation = f"make({typ}, len({value}))"
        else:
            body = f"for key, item := range {value} {{ out[key] = {converted(t.of, 'item', False, False)} }}"
            allocation = f"make({typ}, len({value}))"
        return f"func() {typ} {{ if {value} == nil {{ return nil }}; out := {allocation}; {body}; return out }}()"

    def marshaler(d: Def, name: str) -> list[str]:
        fields = flat_fields(defs, d) if d.kind == "union" else d.fields
        groups: dict[tuple[str, ...], list[str]] = {}
        if d.kind == "union":
            for variant in d.variants:
                required = tuple(sorted(f.name for f in defs[variant].fields if f.required))
                groups.setdefault(required, []).append(defs[variant].tag)
        else:
            groups[tuple(f.name for f in fields if f.required)] = []
        lines = [f"func (v {name}) MarshalJSON() ([]byte, error) {{",
                 f"\ttype plain {d.name}"]
        if d.kind == "union":
            lines.append(f"\tswitch v.{go_field(d.discriminator)} {{")
        for required, tags in groups.items():
            if tags:
                lines.append("\tcase " + ", ".join(json.dumps(tag) for tag in tags) + ":")
            # Shadow only required or recursively wrapped fields. Embedding preserves optional/extraneous
            # fields and their legacy omitempty tags, and avoids marshaling any nested payload twice.
            selected = [f for f in fields if f.name in required or any(ref in wrapped for ref in refs(f.type))]
            lines += ["\t\treturn json.Marshal(struct {", "\t\t\tplain"]
            for f in selected:
                optional = d.kind == "union" or not f.required
                typ = wire_type(f.type, optional, f.pointer)
                tag = f.name + ("" if f.name in required else ",omitempty")
                lines.append(f'\t\t\t{go_field(f.name)} {typ} `json:"{tag}"`')
            lines += ["\t\t}{", "\t\t\tplain: plain(v),"]
            for f in selected:
                value = converted(f.type, "v." + go_field(f.name), d.kind == "union" or not f.required, f.pointer)
                lines.append(f"\t\t\t{go_field(f.name)}: {value},")
            lines.append("\t\t})")
        if d.kind == "union":
            lines += ["\tdefault:", "\t\treturn json.Marshal(plain(v))", "\t}"]
        return lines + ["}", ""]

    hook = defects + "UnknownEnum"
    if any(d.count_unknown for d in defs.values()):
        out += [f"// {hook} is called with a closed enum's name and the raw value each time one with x-unknown \"count\"",
                "// decodes a value it does not know (the value keeps it, and Valid reports false). nil: nothing is",
                "// called. Set it once, before decoding starts.",
                f"var {hook} func(enum, raw string)", ""]

    for d in defs.values():
        if d.union or d.external:
            continue
        if d.kind == "enum" and d.closed:
            out += closed_enum(d, hook)
        elif d.kind == "id":
            out += comment("// ", named(d.name, d.doc) or f"{d.name} is an ID.")
            out += [f"type {d.name} string", "",
                    f"// String returns the ID as it is on the wire.",
                    f"func (v {d.name}) String() string {{ return string(v) }}", ""]
        elif d.kind == "text":
            out += comment("// ", named(d.name, d.doc) or f"{d.name} is a label.")
            out += comment("// ", "It is free text, not a closed set of values.")
            out += [f"type {d.name} string", ""]
        elif d.kind == "tristate":
            out += tristate(d)
        elif d.kind == "opaque":
            out += comment("// ", named(d.name, d.doc) or f"{d.name} is JSON.")
            out += comment("// ", f"It stays opaque: {sentence(d.reason)}")
            out += [f"type {d.name} json.RawMessage", "",
                    "// MarshalJSON writes the JSON as it is (null when empty).",
                    f"func (v {d.name}) MarshalJSON() ([]byte, error) {{ return json.RawMessage(v).MarshalJSON() }}", "",
                    "// UnmarshalJSON keeps a copy of the JSON as it is.",
                    f"func (v *{d.name}) UnmarshalJSON(data []byte) error {{ return (*json.RawMessage)(v).UnmarshalJSON(data) }}",
                    ""]
        elif d.kind == "enum":
            out += comment("// ", named(d.name, d.doc) or f"Values of {d.name}.")
            out.append("const (")
            for v in d.values:
                out.append(f'\t{d.name}{camel(v)} = "{v}"')
            out += [")", "", f"// {plural(d.name)} are the values of {d.name}, in order.",
                    f"var {plural(d.name)} = []string{{{', '.join(json.dumps(v) for v in d.values)}}}", ""]
        elif d.kind == "any":
            out += comment("// ", d.doc) + [f"type {d.name} = json.RawMessage", ""]
        elif d.kind == "struct":
            out += comment("// ", named(d.name, d.doc))
            out.append(f"type {d.name} struct {{")
            for f in d.fields:
                out += field_line(f)
            if d.extra:
                out += ["\t// Extra keys stay at this object's level on the wire; they cannot replace declared fields.",
                        '\tAdditionalProperties map[string]json.RawMessage `json:"-"`']
            out += ["}", ""]
            if d.extra:
                keys = ", ".join(json.dumps(k) for k in reserved_keys(defs, d))
                out += [f"func (v *{d.name}) UnmarshalJSON(data []byte) error {{",
                        "\tvar extra map[string]json.RawMessage",
                        "\tif err := json.Unmarshal(data, &extra); err != nil { return err }",
                        "\tdeclared := map[string]json.RawMessage{}",
                        f"\tfor _, key := range []string{{{keys}}} {{",
                        "\t\tif value, ok := extra[key]; ok { declared[key] = value; delete(extra, key) }", "\t}",
                        "\tdata, err := json.Marshal(declared)", "\tif err != nil { return err }",
                        f"\ttype known {d.name}", "\tvar fields known",
                        "\tif err := json.Unmarshal(data, &fields); err != nil { return err }",
                        "\tfields.AdditionalProperties = extra", f"\t*v = {d.name}(fields)",
                        "\treturn nil", "}", "",
                        f"func (v {d.name}) MarshalJSON() ([]byte, error) {{",
                        f"\ttype known {d.name}", "\tdata, err := json.Marshal(known(v))",
                        "\tif err != nil { return nil, err }",
                        "\tvar fields map[string]json.RawMessage",
                        "\tif err := json.Unmarshal(data, &fields); err != nil { return nil, err }",
                        "\tfor key, value := range v.AdditionalProperties {"]
                if keys:
                    out += ["\t\tswitch key {", f"\t\tcase {keys}:", "\t\t\tcontinue", "\t\t}"]
                out += ["\t\tfields[key] = value", "\t}", "\treturn json.Marshal(fields)", "}", ""]
            elif d.preserve_required and any(ref in wrapped for f in d.fields for ref in refs(f.type)):
                out += marshaler(d, d.name)
        elif d.kind == "union":
            disc = d.discriminator
            out += comment("// ", named(d.name, d.doc) + f" One struct for every variant: {disc} says which fields "
                                  "mean something.")
            tag_type = d.name + go_field(disc) if d.closed else "string"  # x-enum "closed": a named tag type
            out.append(f"type {d.name} struct {{")
            out.append(f"\t{go_field(disc)} {tag_type} `json:\"{disc}\"`")
            for f in flat_fields(defs, d):
                out += field_line(f, force_optional=True)
            out += ["}", ""]
            if d.closed:
                out += comment("// ", f"{tag_type} is which variant a {d.name} is. A {disc} this side does not know "
                                      "keeps its raw string and is not Valid.")
                out += [f"type {tag_type} string", ""]
            out += [f"// {d.name} {disc}s.", "const ("]
            for v in d.variants:
                typed = f" {tag_type}" if d.closed else ""
                out.append(f'\t{d.name}{camel(defs[v].tag)}{typed} = "{defs[v].tag}"')
            out += [")", "", f"// {d.name}{plural(go_field(disc))} are the {disc}s of {d.name}, in order.",
                    f"var {d.name}{plural(go_field(disc))} = []{tag_type}{{"
                    + ", ".join((f"{d.name}{camel(defs[v].tag)}" if d.closed else json.dumps(defs[v].tag))
                                for v in d.variants) + "}", ""]
            if d.closed:
                consts = ", ".join(f"{d.name}{camel(defs[v].tag)}" for v in d.variants)
                out += [f"// Valid reports whether v is one of {d.name}{plural(go_field(disc))}.",
                        f"func (v {tag_type}) Valid() bool {{", "\tswitch v {", f"\tcase {consts}:", "\t\treturn true",
                        "\t}", "\treturn false", "}", ""]
            if d.preserve_required:
                out += marshaler(d, d.name)
            if any(defs[v].since for v in d.variants):
                out += [f"// {d.name}Since is the UI version that brought each {disc}.",
                        f"var {d.name}Since = map[string]int{{"
                        + ", ".join(f"{json.dumps(defs[v].tag)}: {defs[v].since}" for v in d.variants) + "}", ""]
    for name in sorted(wrapped):
        out += [f"// requiredJSON{name} preserves required fields only inside stream payloads.",
                f"type requiredJSON{name} {name}", ""]
        out += marshaler(defs[name], "requiredJSON" + name)
    registered = [d.name for d in defs.values() if d.kind in ("struct", "union") and not d.union]
    if registered:  # a file of IDs or enums only has nothing to read examples into
        out += [f"// {registry} makes a value of each definition, for tests that read examples by definition name.",
                f"var {registry} = map[string]func() any{{"]
        out += [f"\t{json.dumps(name)}: func() any {{ return new({name}) }}," for name in registered]
        out += ["}", ""]
    out += go_calls(calls or [])
    # Go refuses an unused import, and gofmt does not take one out: name encoding/json only when the code uses it.
    uses_json = any(re.search(r"\bjson\.", line) for line in out if not line.lstrip().startswith("//"))
    uses_errors = any(re.search(r"\berrors\.", line) for line in out if not line.lstrip().startswith("//"))
    imports = [f'\t"{p}"' for p, used in (("encoding/json", uses_json), ("errors", uses_errors), ("time", uses_time))
               if used]
    shared = sorted({packages[d.external][0] for d in defs.values() if d.external})
    if shared:
        imports += [""] * bool(imports) + [f'\t"{p}"' for p in shared]
    head = [*(header or GO_HEADER), ""] + ([package_doc] if package_doc else []) + [f"package {package}", ""]
    if imports:
        head += ["import (", *imports, ")", ""]
    return "\n".join(head + out)


def tristate(d: Def) -> list[str]:
    """x-tristate: an optional boolean whose absence means something of its own, as one closed value. A field of it
    is tagged omitzero, so the default stays absent on the wire; null reads as absent too, as a *bool did."""
    n = d.name
    out = comment("// ", named(n, d.doc) or f"{n} is an optional boolean.")
    out += comment("// ", f"It has three values: {n}Default (absent from the JSON), {n}True and {n}False.")
    out += [f"type {n} uint8", "", "const (", f"\t// {n}Default: absent.", f"\t{n}Default {n} = iota",
            f"\t// {n}True: true.", f"\t{n}True", f"\t// {n}False: false.", f"\t{n}False", ")", "",
            f"// IsZero reports {n}Default, which omitzero leaves out of the JSON.",
            f"func (v {n}) IsZero() bool {{ return v == {n}Default }}", "",
            "// Or is the boolean v says, or absent when v is the default.",
            f"func (v {n}) Or(absent bool) bool {{", "\tswitch v {", f"\tcase {n}True:", "\t\treturn true",
            f"\tcase {n}False:", "\t\treturn false", "\t}", "\treturn absent", "}", "",
            *comment("// ", f"MarshalJSON writes true or false; {n}Default is null (a field tagged omitzero leaves it "
                                 "out instead)."),
            f"func (v {n}) MarshalJSON() ([]byte, error) {{", "\tswitch v {", f"\tcase {n}Default:",
            '\t\treturn []byte("null"), nil', f"\tcase {n}True:", '\t\treturn []byte("true"), nil',
            f"\tcase {n}False:", '\t\treturn []byte("false"), nil', "\t}",
            f'\treturn nil, errors.New("{n}: not one of its three values")', "}", "",
            "// UnmarshalJSON reads true or false, and null as absent; anything else fails.",
            f"func (v *{n}) UnmarshalJSON(data []byte) error {{", '\tif string(data) == "null" {',
            f"\t\t*v = {n}Default", "\t\treturn nil", "\t}", "\tvar b bool",
            "\tif err := json.Unmarshal(data, &b); err != nil {", "\t\treturn err", "\t}",
            f"\t*v = {n}False", "\tif b {", f"\t\t*v = {n}True", "\t}", "\treturn nil", "}", ""]
    return out


def closed_enum(d: Def, hook: str) -> list[str]:
    """x-enum "closed": a named string type, its constants and ordered list, Valid; with x-unknown "count" an
    UnmarshalJSON that keeps an unknown value as it came and calls the hook."""
    consts = [f"{d.name}{camel(v)}" for v in d.values]
    out = comment("// ", named(d.name, d.doc) or f"{d.name} is a closed set of values.")
    out += comment("// ", "A value this side does not know keeps its raw string and is not Valid.")
    out += [f"type {d.name} string", "", "const ("]
    out += [f'\t{c} {d.name} = "{v}"' for c, v in zip(consts, d.values)]
    out += [")", "", f"// {plural(d.name)} are the values of {d.name}, in order.",
            f"var {plural(d.name)} = []{d.name}{{{', '.join(consts)}}}", "",
            f"// Valid reports whether v is one of {plural(d.name)}.",
            f"func (v {d.name}) Valid() bool {{", "\tswitch v {", f"\tcase {', '.join(consts)}:", "\t\treturn true",
            "\t}", "\treturn false", "}", ""]
    if d.count_unknown:
        out += [f"// UnmarshalJSON keeps any string; one that is not Valid is reported to {hook}.",
                f"func (v *{d.name}) UnmarshalJSON(data []byte) error {{", "\tvar raw string",
                "\tif err := json.Unmarshal(data, &raw); err != nil {", "\t\treturn err", "\t}",
                f"\t*v = {d.name}(raw)", f"\tif !v.Valid() && {hook} != nil {{", f'\t\t{hook}("{d.name}", raw)', "\t}",
                "\treturn nil", "}", ""]
    return out


def gofmt(src: str) -> str:
    exe = shutil.which("gofmt")
    if not exe:
        raise SchemaError("gofmt is not on PATH: the Go output is gofmt's")
    r = subprocess.run([exe], input=src, capture_output=True, text=True)
    if r.returncode != 0:
        raise SchemaError("gofmt: " + r.stderr.strip())
    return r.stdout
